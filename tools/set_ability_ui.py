def read(data):
    assert struct.unpack_from('<I', data)[0] == 1
    pos, tables = 4, []
    for _ in range(2):
        count, = struct.unpack_from('<I', data, pos); pos += 4
        objects = []
        for _ in range(count):
            old, new, count = struct.unpack_from('<4s4sI', data, pos); pos += 12
            fields = []
            for _ in range(count):
                field, kind, level, pointer = struct.unpack_from('<4s3I', data, pos); pos += 16
                end = data.index(0, pos) + 1 if kind == 3 else pos + 4
                fields.append((field, kind, level, pointer, data[pos:end], data[end:end+4]))
                pos = end + 4
            objects.append((old, new, fields))
        tables.append(objects)
    assert pos == len(data)
    return tables


def apply():
    path = ROOT / 'war3map.w3a'
    tables = read(path.read_bytes())
    objects = {new.decode(): fields for _, new, fields in tables[1]}
    for index, (raw, name, icon, target, description) in enumerate(SPELLS):
        fields = objects[raw]
        slot = index % 4
        key = 'QWER'[slot]
        changes = []
        def add(field, value, level=0, pointer=0):
            kind = 3 if isinstance(value, str) else 0
            encoded = value.encode('utf-8') + b'\0' if kind == 3 else struct.pack('<i', value)
            changes.append((field.encode(), kind, level, pointer, encoded, b'\0'*4))
        add('anam', name)
        add('aart', 'ReplaceableTextures\\CommandButtons\\'+icon+'.blp')
        add('aher', 0)
        add('ahky', key)
        add('abpx', slot)
        add('abpy', 2)
        for level in range(1, 6):
            # The client appends the hotkey automatically from ahky.
            add('atp1', f'{name} — Ранг {level}/5', level)
            add('aub1', numbers(raw,level) + '|n|n' + description, level)
            # Channel must actually provide the target expected by the Lua handler.
            add('Ncl2', target, level, 2)
            add('Ncl3', 19 if raw in TARGET_AREAS else 17, level, 3)
            if raw in TARGET_AREAS:
                changes.append((b'aare',2,level,0,struct.pack('<f',float(TARGET_AREAS[raw])),b'\0'*4))
            if raw == 'A11F':
                changes.append((b'acdn',2,level,0,struct.pack('<f',16.0),b'\0'*4))
            if target:
                cast_range = 1200.0 if raw in ('A105','A106','A109') else 900.0
                changes.append((b'aran', 1, level, 0, struct.pack('<f', cast_range), b'\0'*4))
                add('atar', 'air,ground,invulnerable,vulnerable', level)
        keys = {(f, level) for f, _, level, _, _, _ in changes}
        fields[:] = [entry for entry in fields if (entry[0], entry[2]) not in keys]
        fields.extend(changes)
    # Wind Walk must be a native invisibility ability, not a Channel+invulnerability stub.
    for index,(old,new,fields) in enumerate(tables[1]):
        if new == b'A104':
            fields[:] = [entry for entry in fields if not entry[0].startswith(b'Ncl')
                         and entry[0] not in (b'Owk1',b'Owk2',b'Owk3',b'adur',b'ahdu')]
            for level in range(1,6):
                for field,amount,pointer in [(b'Owk1',0.15,1),(b'Owk2',0.2,2),(b'Owk3',0.0,3),
                                             (b'adur',5.0,0),(b'ahdu',5.0,0)]:
                    fields.append((field,2,level,pointer,struct.pack('<f',amount),b'\0'*4))
            tables[1][index]=(b'AOwk',new,fields)
    result = bytearray(struct.pack('<I', 1))
    for objects in tables:
        result.extend(struct.pack('<I', len(objects)))
        for old, new, fields in objects:
            result.extend(struct.pack('<4s4sI', old, new, len(fields)))
            for field, kind, level, pointer, value, marker in normalize(fields):
                result.extend(struct.pack('<4s3I', field, kind, level, pointer)+value+marker)
    path.write_bytes(result)
    print('Updated names, descriptions, icons and targeting for 40 abilities')


if __name__ == '__main__':
    apply()
